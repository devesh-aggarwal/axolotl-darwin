#!/usr/bin/env node
// Turns two `claude -p --output-format stream-json --verbose` logs into the event list replay.html plays.
// Usage: node scripts/demo-video/build-transcripts.mjs <without.jsonl> <with.jsonl> [hook.log] > scripts/demo-video/transcripts.js
import { readFileSync, existsSync } from "node:fs";

const SHORT = { "mcp__uber-eats__search_uber_eats": "Uber Eats · search", "mcp__axolotl__axolotl_resolve_place": "Axolotl · resolve place", "mcp__axolotl__axolotl_recover": "Axolotl · recover", "mcp__axolotl__axolotl_add_to_cart": "Axolotl · add to cart" };

function textOf(content) {
  if (typeof content === "string") return content;
  return (content ?? []).map((c) => c.text ?? "").join("\n");
}

function summarize(tool, input, raw, isError) {
  let data = null;
  try { data = JSON.parse(raw); } catch { /* plain text */ }
  if (tool.endsWith("search_uber_eats")) {
    if (isError || !data) return { ok: false, text: raw.split("\n")[0] };
    return { ok: true, text: `${data.results.length} dishes found near ${input.delivery_address}` };
  }
  if (tool.endsWith("resolve_place") && data) {
    return { ok: data.status === "resolved", text: data.place ? `${data.place.address}` : data.status, attempts: data.attempts };
  }
  if (tool.endsWith("recover") && data) return { ok: true, text: `${data.kind.replace("_", " ")}: ${data.nextAction}` };
  if (tool.endsWith("add_to_cart") && data) {
    const c = data.cart;
    return { ok: Boolean(c), text: c ? `${c.items[0].quantity} × ${c.items[0].name}, ${c.restaurant} · $${c.totalUsd.toFixed(2)} → ${c.deliverTo}` : data.status, attempts: data.attempts, simulated: true };
  }
  return { ok: !isError, text: raw.slice(0, 160) };
}

function events(file) {
  const out = [];
  const pending = new Map();
  let durationMs = 0;
  let costUsd = 0;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    let e;
    try { e = JSON.parse(line); } catch { continue; }
    if (e.type === "assistant") {
      for (const c of e.message.content) {
        if (c.type === "text" && c.text.trim()) out.push({ kind: "say", text: c.text.trim() });
        if (c.type === "tool_use" && c.name !== "ToolSearch") {
          const ev = { kind: "tool", tool: SHORT[c.name] ?? c.name, input: c.input };
          pending.set(c.id, ev);
          out.push(ev);
        }
      }
    } else if (e.type === "user" && Array.isArray(e.message.content)) {
      for (const c of e.message.content) {
        const ev = c.type === "tool_result" && pending.get(c.tool_use_id);
        if (ev) Object.assign(ev, { result: summarize(Object.keys(SHORT).find((k) => SHORT[k] === ev.tool) ?? ev.tool, ev.input, textOf(c.content), c.is_error) });
      }
    } else if (e.type === "result") {
      durationMs = e.duration_ms;
      costUsd = e.total_cost_usd;
    }
  }
  return { events: out, durationMs, costUsd };
}

const [without, withAx, hookLog] = process.argv.slice(2);
const a = events(without);
const b = events(withAx);
// The Stop hook isn't in the stream; place its block where it happened: after the first give-up reply.
if (hookLog && existsSync(hookLog)) {
  const block = readFileSync(hookLog, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l)).find((h) => h.decision === "block");
  const firstSay = b.events.findIndex((ev) => ev.kind === "say");
  if (block && firstSay >= 0) b.events.splice(firstSay + 1, 0, { kind: "hook", matched: block.matched });
}
process.stdout.write(`// Generated by build-transcripts.mjs from two real headless Claude Code runs. Do not edit by hand.\nwindow.TRANSCRIPTS = ${JSON.stringify({ without: a, with: b }, null, 1)};\n`);
